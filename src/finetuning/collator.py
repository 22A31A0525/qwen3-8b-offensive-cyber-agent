"""collator.py
Custom CompletionLossDataCollator for Qwen3-8B (v3 Pipeline).

Enforces:
1. labels = -100 on system prompt, tool definitions, user prompts, and tool returns.
2. Only tokens generated by the assistant receive active training gradients.
3. Supports dynamic padding and fixed max_length (4,096).
"""
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Union
import torch


@dataclass
class CompletionLossDataCollator:
    """Collator that restricts loss computation strictly to assistant turns."""
    tokenizer: Any
    response_template: str = "<|im_start|>assistant\n"
    instruction_template: str = "<|im_end|>\n"
    max_length: int = 4096
    pad_to_multiple_of: Optional[int] = 8

    def __call__(self, features: List[Dict[str, Any]]) -> Dict[str, torch.Tensor]:
        input_ids_list = [f["input_ids"] for f in features]
        
        # Calculate max length in batch bounded by max_length
        max_batch_len = min(max(len(ids) for ids in input_ids_list), self.max_length)
        if self.pad_to_multiple_of is not None:
            max_batch_len = (
                (max_batch_len + self.pad_to_multiple_of - 1)
                // self.pad_to_multiple_of
                * self.pad_to_multiple_of
            )
            
        pad_token_id = getattr(self.tokenizer, "pad_token_id", 0) or 0
        
        batch_input_ids = []
        batch_attention_mask = []
        batch_labels = []

        resp_ids = self.tokenizer.encode(self.response_template, add_special_tokens=False)
        inst_ids = self.tokenizer.encode(self.instruction_template, add_special_tokens=False)
        n_resp = len(resp_ids)
        n_inst = len(inst_ids)

        for raw_ids in input_ids_list:
            # Truncate if necessary
            ids = raw_ids[:self.max_length]
            seq_len = len(ids)
            
            # Masking logic
            labels = [-100] * seq_len
            i = 0
            while i < seq_len:
                if ids[i : i + n_resp] == resp_ids:
                    start_idx = i + n_resp
                    end_idx = seq_len
                    for j in range(start_idx, seq_len):
                        if ids[j : j + n_inst] == inst_ids:
                            end_idx = j
                            break
                    for k in range(start_idx, min(end_idx + 1, seq_len)):
                        labels[k] = ids[k]
                    i = end_idx + n_inst
                else:
                    i += 1

            # Padding
            pad_len = max_batch_len - seq_len
            padded_ids = ids + [pad_token_id] * pad_len
            padded_mask = [1] * seq_len + [0] * pad_len
            padded_labels = labels + [-100] * pad_len

            batch_input_ids.append(padded_ids)
            batch_attention_mask.append(padded_mask)
            batch_labels.append(padded_labels)

        return {
            "input_ids": torch.tensor(batch_input_ids, dtype=torch.long),
            "attention_mask": torch.tensor(batch_attention_mask, dtype=torch.long),
            "labels": torch.tensor(batch_labels, dtype=torch.long),
        }

